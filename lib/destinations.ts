export const destinationCountries = codes.map((code) => ({ code, name: names.of(code) || code })).sort((a, b) => a.name.localeCompare(b.name, "ko"));
const normalize = (value: string) => value.trim().toLowerCase().replace(/\s/g, "");
export function destinationCountryCode(country: string) {
  if (["한국", "대한민국", "southkorea", "korea"].includes(normalize(country))) return "KR";
  return destinationCountries.find((item) => [item.code, item.name, englishNames.of(item.code) || ""].some((name) => normalize(name) === normalize(country)))?.code;
}
